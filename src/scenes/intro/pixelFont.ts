/** Returns block coordinates (x right, y up) for a string, centred on x = 0. */
export function textToBlocks(text: string) {
  const chars = text.toUpperCase().split('')
  const blocks: [number, number][] = []
  const advance = 6
  const width = chars.length * advance - 1
  chars.forEach((ch, ci) => {
    const glyph = FONT[ch] ?? FONT[' ']
    glyph.forEach((row, ry) => {
      row.split('').forEach((cell, rx) => {
        if (cell === '#') blocks.push([ci * advance + rx - width / 2 + 0.5, 6 - ry])
      })
    })
  })
  return { blocks, width }
}
